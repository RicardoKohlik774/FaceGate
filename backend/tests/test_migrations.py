"""The migrations work in both directions and match the Python table classes."""
from alembic import command
from alembic.util.exc import AutogenerateDiffsDetected

from tests.conftest import alembic_config


def test_downgrade_to_empty_and_upgrade_again(migrated_test_database):
    config = alembic_config()
    command.downgrade(config, "base")  # remove every table
    command.upgrade(config, "head")  # and build them again


def test_database_matches_the_models(migrated_test_database):
    # Fails if someone changed app/models.py but forgot to write a migration.
    try:
        command.check(alembic_config())
    except AutogenerateDiffsDetected as error:
        raise AssertionError(f"models.py and the migrations differ: {error}") from None
